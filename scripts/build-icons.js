/**
 * Icon library generator.
 *
 * Reads scripts/icons.manifest.json (the single source of truth) and the
 * lucide-static SVG set, then regenerates BOTH:
 *   - src/components/iconLibrary.js  (editor: ICON_LIBRARY + ICON_META + ICON_SLUGS)
 *   - inc/Blocks/Icons.php           (frontend: AxiomBlocks\Blocks\Icons)
 *
 * Run `npm run build:icons` after editing the manifest, then commit both files.
 * Generated output is then linted/aligned by ESLint + PHPCBF (CI/dev), so it
 * does not need to be pixel-perfect here.
 *
 * Icons are Lucide (ISC). lucide-static is a dev dependency only — nothing from
 * node_modules ships; the SVG markup is inlined into the two generated files.
 */

/* eslint-disable no-console */
const fs = require( 'fs' );
const path = require( 'path' );

const ROOT = path.join( __dirname, '..' );
const MANIFEST = path.join( __dirname, 'icons.manifest.json' );
const ICON_DIR = path.join( ROOT, 'node_modules', 'lucide-static', 'icons' );
const OUT_JS = path.join( ROOT, 'src', 'components', 'iconLibrary.js' );
const OUT_PHP = path.join( ROOT, 'inc', 'Blocks', 'Icons.php' );

const SVG_OPEN =
	'<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">';

// SVG attribute names that must become camelCase to be valid JSX.
const JSX_ATTRS = {
	'stroke-width': 'strokeWidth',
	'stroke-linecap': 'strokeLinecap',
	'stroke-linejoin': 'strokeLinejoin',
	'stroke-miterlimit': 'strokeMiterlimit',
	'stroke-dasharray': 'strokeDasharray',
	'stroke-dashoffset': 'strokeDashoffset',
	'stroke-opacity': 'strokeOpacity',
	'fill-rule': 'fillRule',
	'fill-opacity': 'fillOpacity',
	'clip-rule': 'clipRule',
	'clip-path': 'clipPath',
	class: 'className',
};

function innerOf( svg ) {
	const m = svg.match( /<svg[^>]*>([\s\S]*?)<\/svg>/i );
	if ( ! m ) {
		throw new Error( 'Could not parse SVG inner markup' );
	}
	return m[ 1 ].replace( /\s+/g, ' ' ).trim();
}

function toJsx( inner ) {
	let s = inner;
	for ( const [ from, to ] of Object.entries( JSX_ATTRS ) ) {
		s = s.split( `${ from }=` ).join( `${ to }=` );
	}
	return s;
}

function load() {
	const manifest = JSON.parse( fs.readFileSync( MANIFEST, 'utf8' ) ).icons;
	const seen = new Set();
	return manifest.map( ( it ) => {
		if ( seen.has( it.slug ) ) {
			throw new Error( `Duplicate slug in manifest: ${ it.slug }` );
		}
		seen.add( it.slug );
		const name = it.lucide || it.slug;
		const file = path.join( ICON_DIR, `${ name }.svg` );
		if ( ! fs.existsSync( file ) ) {
			throw new Error(
				`Icon "${ it.slug }" → lucide "${ name }" not found at ${ file }`
			);
		}
		return { ...it, inner: innerOf( fs.readFileSync( file, 'utf8' ) ) };
	} );
}

function buildJs( rows ) {
	const lib = rows
		.map(
			( r ) =>
				`\t'${ r.slug }': (\n\t\t<Svg>${ toJsx( r.inner ) }</Svg>\n\t),`
		)
		.join( '\n' );

	const meta = rows
		.map(
			( r ) =>
				`\t{ slug: '${ r.slug }', label: __( '${ r.label.replace(
					/'/g,
					"\\'"
				) }', 'axiom-blocks' ), category: '${
					r.category
				}', keywords: '${ r.keywords }' },`
		)
		.join( '\n' );

	return `/**
 * Shared curated icon library (Lucide outline, 24×24, 2px stroke).
 *
 * GENERATED by scripts/build-icons.js from scripts/icons.manifest.json — do not
 * edit by hand. Add/remove icons in the manifest, then run \`npm run build:icons\`.
 * Keep in sync with inc/Blocks/Icons.php (the generator writes both).
 *
 * Icons are referenced by slug and the SVG is resolved at render time, so the
 * set can grow without saved-markup migrations. No width/height on the shell —
 * size is controlled by the consuming block's CSS.
 */

import { __ } from '@wordpress/i18n';

const Svg = ( { children } ) => (
	<svg
		viewBox="0 0 24 24"
		fill="none"
		stroke="currentColor"
		strokeWidth="2"
		strokeLinecap="round"
		strokeLinejoin="round"
		aria-hidden="true"
	>
		{ children }
	</svg>
);

export const ICON_LIBRARY = {
${ lib }
};

/**
 * Picker metadata — label + search keywords + category, in display order.
 * \`slug\` always exists in ICON_LIBRARY (and Icons.php).
 */
export const ICON_META = [
${ meta }
];

/** Flat slug list (render order / validation). */
export const ICON_SLUGS = ICON_META.map( ( i ) => i.slug );
`;
}

function buildPhp( rows ) {
	const entries = rows
		.map( ( r ) => `\t\t\t'${ r.slug }' => $o . '${ r.inner }</svg>',` )
		.join( '\n' );

	return `<?php
/**
 * Icons — shared curated icon library (Lucide outline, 24×24, 2px stroke).
 *
 * GENERATED by scripts/build-icons.js from scripts/icons.manifest.json — do not
 * edit by hand. Add/remove icons in the manifest, then run \`npm run build:icons\`.
 * The frontend counterpart of src/components/iconLibrary.js (generator writes both).
 *
 * No width/height on the shell — size is controlled by the consuming block's CSS.
 *
 * @package AxiomBlocks\\Blocks
 * @since 1.1.0
 */

namespace AxiomBlocks\\Blocks;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Shared icon library helper.
 *
 * @since 1.1.0
 */
class Icons {

	private const OPEN = '${ SVG_OPEN }';

	/**
	 * Full slug → inline SVG map.
	 *
	 * @return array<string, string>
	 */
	public static function all(): array {
		$o = self::OPEN;
		return array(
${ entries }
		);
	}

	/**
	 * Resolve a single icon by slug. Returns '' for unknown slugs.
	 *
	 * @param string $slug Icon slug.
	 * @return string Inline SVG markup, or empty string.
	 */
	public static function get( string $slug ): string {
		$all = self::all();
		return $all[ $slug ] ?? '';
	}
}
`;
}

function main() {
	const rows = load();
	fs.writeFileSync( OUT_JS, buildJs( rows ), 'utf8' );
	fs.writeFileSync( OUT_PHP, buildPhp( rows ), 'utf8' );
	console.log(
		`Generated ${ rows.length } icons → src/components/iconLibrary.js + inc/Blocks/Icons.php`
	);
}

main();
